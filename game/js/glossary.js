const GLOSS_RE = (() => {
  const all = []; GLOSS.forEach(g => g.k.forEach(k => all.push([k, g.id])));
  all.sort((a, b) => b[0].length - a[0].length);
  const map = {}; all.forEach(([k, id]) => { map[k] = id; });
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return { re: new RegExp(all.map(a => esc(a[0])).join('|'), 'g'), map };
})();
const GLOSS_BY = Object.fromEntries(GLOSS.map(g => [g.id, g]));

// 요소 안의 글자에서 용어를 찾아 밑줄 표시 (같은 용어는 한 번만)
function glossify(root) {
  if (!root) return;
  const seen = new Set(), walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), nodes = [];
  while (walker.nextNode()) { const n = walker.currentNode; if (n.parentElement && n.parentElement.closest('.term, code, button, .symleg')) continue; nodes.push(n); }
  nodes.forEach(node => {
    const txt = node.nodeValue; GLOSS_RE.re.lastIndex = 0;
    let m, last = 0, frag = null;
    while ((m = GLOSS_RE.re.exec(txt))) {
      const id = GLOSS_RE.map[m[0]]; if (seen.has(id)) continue; seen.add(id);
      frag = frag || document.createDocumentFragment();
      frag.appendChild(document.createTextNode(txt.slice(last, m.index)));
      const sp = document.createElement('span'); sp.className = 'term'; sp.dataset.g = id; sp.textContent = m[0]; frag.appendChild(sp);
      last = m.index + m[0].length;
    }
    if (frag) { frag.appendChild(document.createTextNode(txt.slice(last))); node.parentNode.replaceChild(frag, node); }
  });
}
// 말풍선
(function initGlossTip() {
  const tip = document.createElement('div'); tip.id = 'gtip'; document.body.appendChild(tip);
  let cur = null;
  const show = el => {
    const g = GLOSS_BY[el.dataset.g]; if (!g) return; cur = el;
    tip.innerHTML = `<div class="gt-t">📘 ${g.t}</div><div class="gt-d">${g.d}</div><div class="gt-e"><b>예시</b> ${g.e}</div>`;
    tip.classList.add('on');
    const r = el.getBoundingClientRect(), tw = Math.min(320, window.innerWidth - 16);
    tip.style.width = tw + 'px';
    let x = r.left + r.width / 2 - tw / 2; x = Math.max(8, Math.min(window.innerWidth - tw - 8, x));
    tip.style.left = x + 'px';
    const h = tip.offsetHeight;
    tip.style.top = (r.top - h - 10 > 8 ? r.top - h - 10 : r.bottom + 10) + 'px';
  };
  const hide = () => { tip.classList.remove('on'); cur = null; };
  document.addEventListener('mouseover', e => { const t = e.target.closest && e.target.closest('.term'); if (t) show(t); else if (cur && !e.target.closest('#gtip')) hide(); });
  document.addEventListener('click', e => { const t = e.target.closest && e.target.closest('.term'); if (t) { e.stopPropagation(); if (cur === t) hide(); else show(t); } else if (cur) hide(); }, true);
  window.addEventListener('scroll', hide, true);
})();
