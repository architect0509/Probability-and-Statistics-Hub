// 개념 이름의 핵심 낱말 (괄호 빼고)
function conceptKeys(c) {
  const base = c.t.replace(/\(.*?\)/g, '').trim();
  const parts = base.split(/과|와|·|,|\s+vs\s+/).map(s => s.trim()).filter(s => s.length >= 2);
  return [base].concat(parts);
}
// 문제와 가장 관련 깊은 개념 찾기
function conceptsFor(q) {
  const h = (typeof QUIZ_HELP !== 'undefined' && QUIZ_HELP[q.id]) || {};
  const txt = [q.q, q.a, q.ex, h.f || '', (h.s || []).join(' ')].join(' ');
  if (q.concept) return HUB_CONCEPTS.filter(c => c.t === q.concept);
  const scored = HUB_CONCEPTS.map(c => {
    let sc = 0;
    conceptKeys(c).forEach(k => { if (txt.includes(k)) sc += k.length * 2; });
    (c.k || '').split(/\s+/).forEach(k => { if (k.length >= 2 && /[가-힣]/.test(k) && txt.includes(k)) sc += 1; });
    if (q.ch && c.ch === q.ch) sc += .5;
    return [sc, c];
  }).filter(x => x[0] >= 4).sort((a, b) => b[0] - a[0]);
  return scored.slice(0, 2).map(x => x[1]);
}
// 이지 쌤의 쉬운 비유 한 토막
function easyFor(q) {
  if (typeof EASY === 'undefined') return null;
  const txt = [q.q, q.a, q.ex, q.concept || ''].join(' ');
  const e = EASY.find(e => e.k.some(k => txt.includes(k)));
  if (!e) return null;
  const first = e.x.split('\n\n')[0];
  return { t: e.t, x: first };
}
function conceptBoxHTML(q) {
  const cs = conceptsFor(q), ez = easyFor(q);
  if (!cs.length && !ez) return '';
  let h = '<div class="cbox"><div class="cbox-h">📘 개념 다시 보기 <small>확통허브 개념사전</small></div>';
  cs.forEach(c => { h += `<div class="cbox-c"><b>${esc(c.t)}</b> <span class="cbox-ch">${c.ch}장</span><div>${esc(c.d)}</div>${c.e ? `<div class="cbox-e">예) ${esc(c.e)}</div>` : ''}</div>`; });
  if (ez) h += `<div class="cbox-z">💡 <b>쉽게 말하면</b> — ${esc(ez.x).replace(/\n/g, ' ')}</div>`;
  return h + '</div>';
}

